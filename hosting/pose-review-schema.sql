CREATE TABLE IF NOT EXISTS pose_records(id TEXT PRIMARY KEY, revision INTEGER NOT NULL, record TEXT NOT NULL CHECK(json_valid(record)));
CREATE TABLE IF NOT EXISTS pose_revisions(id TEXT NOT NULL, revision INTEGER NOT NULL, record TEXT NOT NULL, saved_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(id,revision));
CREATE TRIGGER IF NOT EXISTS pose_record_history BEFORE UPDATE ON pose_records BEGIN
 INSERT INTO pose_revisions(id,revision,record) VALUES(OLD.id,OLD.revision,OLD.record);
END;
CREATE TABLE IF NOT EXISTS pose_files(path TEXT PRIMARY KEY, digest TEXT NOT NULL, size INTEGER NOT NULL, mime TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS pose_sessions(digest TEXT PRIMARY KEY, actor TEXT NOT NULL, csrf TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS pose_agents(digest TEXT PRIMARY KEY, worker TEXT NOT NULL UNIQUE, created INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS pose_settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
